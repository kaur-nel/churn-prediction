from pathlib import Path

import pytest

from src.pin_requirements import (
    PIN_FILES,
    PinError,
    installed_version,
    normalize,
    parse_requirements,
    pin_names,
    run_pin,
)

REPO_ROOT = Path(__file__).resolve().parents[1]
VERSIONS = {"pandas": "2.0.1", "numpy": "1.26.4", "pytest": "8.0.0", "ruff": "0.5.0", "seaborn": "0.13.0"}


def fake_lookup(name: str) -> str:
    try:
        return VERSIONS[name.lower()]
    except KeyError as exc:
        raise PinError(f"Package '{name}' is not installed in this environment") from exc


# ---------- parsing ------------------------------------------------------------------------


def test_plain_names_are_read_in_order():
    assert parse_requirements("pandas\nnumpy\n") == (["pandas", "numpy"], [])


def test_comments_blank_lines_specifiers_and_markers_are_ignored():
    text = "# heading\n\npandas>=2.0,<3  # comment\nnumpy ; python_version >= '3.9'\n"
    assert parse_requirements(text) == (["pandas", "numpy"], [])


def test_duplicates_are_removed_ignoring_case_and_separators():
    names, _ = parse_requirements("Scikit_Learn\nscikit-learn\nSCIKIT.LEARN\n")
    assert names == ["Scikit_Learn"]


def test_includes_are_collected():
    assert parse_requirements("-r requirements.in\npytest\n") == (["pytest"], ["requirements.in"])
    assert parse_requirements("-rrequirements.in\n") == ([], ["requirements.in"])


@pytest.mark.parametrize(
    ("text", "message"),
    [
        ("-e .", "unsupported"),
        ("https://example.com/p.whl", "unsupported"),
        ("pkg @ https://example.com/p.whl", "unsupported"),
        ("==1.0", "does not start"),
        ("pandas foo", "unexpected text"),
        ("numpy[extra]", "extras"),
        ("-r", "needs a file"),
        ("", "lists no packages"),
        ("# only a comment\n", "lists no packages"),
    ],
)
def test_bad_lines_raise_with_a_clear_message(text, message):
    with pytest.raises(PinError, match=message):
        parse_requirements(text)


def test_error_message_names_the_line():
    with pytest.raises(PinError, match=r"requirements\.in:2"):
        parse_requirements("pandas\n-e .\n", "requirements.in")


def test_normalize():
    assert normalize("Scikit_Learn") == "scikit-learn"
    assert normalize("python.dotenv") == "python-dotenv"


# ---------- pinning ------------------------------------------------------------------------


def test_pin_names_uses_the_lookup():
    assert pin_names(["pandas", "numpy"], fake_lookup) == ["pandas==2.0.1", "numpy==1.26.4"]


def test_pin_names_lists_every_missing_package():
    with pytest.raises(PinError, match=r"nosuch1.*nosuch2"):
        pin_names(["pandas", "nosuch1", "nosuch2"], fake_lookup)


def test_installed_version_reads_the_environment():
    assert installed_version("pytest")
    with pytest.raises(PinError, match="not installed"):
        installed_version("definitely-not-an-installed-package-xyz")


# ---------- writing the files ----------------------------------------------------------------


def write_inputs(root: Path) -> None:
    (root / "requirements.in").write_text("pandas\nnumpy\n", encoding="utf-8")
    (root / "requirements-dev.in").write_text("-r requirements.in\npytest\nruff\n", encoding="utf-8")
    (root / "requirements-notebook.in").write_text("-r requirements.in\nseaborn\n", encoding="utf-8")


def test_run_pin_writes_all_three_files(tmp_path):
    write_inputs(tmp_path)
    written = run_pin(tmp_path, fake_lookup)

    assert set(written) == set(PIN_FILES.values())
    runtime = (tmp_path / "requirements.txt").read_text(encoding="utf-8")
    assert "pandas==2.0.1" in runtime and "numpy==1.26.4" in runtime
    dev = (tmp_path / "requirements-dev.txt").read_text(encoding="utf-8")
    assert "-r requirements.txt" in dev
    assert "pytest==8.0.0" in dev and "ruff==0.5.0" in dev
    assert "pandas" not in dev
    notebook = (tmp_path / "requirements-notebook.txt").read_text(encoding="utf-8")
    assert "-r requirements.txt" in notebook and "seaborn==0.13.0" in notebook


def test_output_is_reproducible_and_uses_unix_line_endings(tmp_path):
    write_inputs(tmp_path)
    run_pin(tmp_path, fake_lookup)
    first = (tmp_path / "requirements.txt").read_bytes()
    run_pin(tmp_path, fake_lookup)
    assert (tmp_path / "requirements.txt").read_bytes() == first
    assert b"\r" not in first
    assert first.endswith(b"\n")
    assert first.startswith(b"# Generated by")


def test_optional_files_are_skipped_when_absent(tmp_path):
    (tmp_path / "requirements.in").write_text("pandas\n", encoding="utf-8")
    assert set(run_pin(tmp_path, fake_lookup)) == {"requirements.txt"}


def test_missing_requirements_in_raises(tmp_path):
    with pytest.raises(PinError, match="not found"):
        run_pin(tmp_path, fake_lookup)


def test_include_of_an_unknown_file_raises(tmp_path):
    (tmp_path / "requirements.in").write_text("-r other.in\npandas\n", encoding="utf-8")
    with pytest.raises(PinError, match="unknown file"):
        run_pin(tmp_path, fake_lookup)


def test_include_of_a_file_that_does_not_exist_raises(tmp_path):
    (tmp_path / "requirements.in").write_text("pandas\n", encoding="utf-8")
    (tmp_path / "requirements-dev.in").write_text("-r requirements-notebook.in\npytest\n", encoding="utf-8")
    with pytest.raises(PinError, match="does not exist"):
        run_pin(tmp_path, fake_lookup)


def test_a_missing_package_writes_nothing(tmp_path):
    (tmp_path / "requirements.in").write_text("pandas\n", encoding="utf-8")
    (tmp_path / "requirements-dev.in").write_text("-r requirements.in\nnosuchpkg\n", encoding="utf-8")
    with pytest.raises(PinError, match="nosuchpkg"):
        run_pin(tmp_path, fake_lookup)
    assert not (tmp_path / "requirements.txt").exists()


def test_an_unwritable_output_raises(tmp_path):
    (tmp_path / "requirements.in").write_text("pandas\n", encoding="utf-8")
    (tmp_path / "requirements.txt").mkdir()
    with pytest.raises(PinError, match="Cannot write"):
        run_pin(tmp_path, fake_lookup)


# ---------- the committed files ----------------------------------------------------------------


@pytest.mark.parametrize("source", sorted(PIN_FILES))
def test_committed_pins_cover_every_package_in_the_in_files(source):
    source_path, target_path = REPO_ROOT / source, REPO_ROOT / PIN_FILES[source]
    if not (source_path.exists() and target_path.exists()):
        pytest.skip(f"{source} or {PIN_FILES[source]} is not present")
    names, includes = parse_requirements(source_path.read_text(encoding="utf-8"), source)
    lines = target_path.read_text(encoding="utf-8").splitlines()
    pinned = {normalize(line.split("==")[0]) for line in lines if "==" in line}
    assert {normalize(name) for name in names} <= pinned, "re-run `python -m src.pin_requirements`"
    for include in includes:
        assert f"-r {PIN_FILES[include]}" in lines