"""Pin the direct dependencies listed in the requirements*.in files to the versions installed here.

requirements.in lists the packages the project imports; requirements-dev.in adds the tools for tests
and linting; requirements-notebook.in adds the exploration notebook's tools. Running this module writes
the matching requirements*.txt files with exact versions (name==version) read from this environment.

Only DIRECT dependencies are pinned. Their own dependencies are chosen by pip at install time. That keeps
the files free of platform-specific packages (a full `pip freeze` from Windows contains Windows-only
packages such as pywin32 that cannot be installed on Linux). The trade-off: an install in a few months may
pick newer versions of those indirect packages.
"""

import importlib.metadata
import re
import sys
from collections.abc import Callable
from pathlib import Path

PIN_FILES = {
    "requirements.in": "requirements.txt",
    "requirements-dev.in": "requirements-dev.txt",
    "requirements-notebook.in": "requirements-notebook.txt",
}
REQUIRED_INPUT = "requirements.in"
_NAME = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]*")


class PinError(Exception):
    """Raised when requirements cannot be read or pinned."""


def normalize(name: str) -> str:
    """Canonical form of a package name (lower case, runs of - _ . become one -)."""
    return re.sub(r"[-_.]+", "-", name).lower()


def installed_version(name: str) -> str:
    """The installed version of a package.

    Raises:
        PinError: if the package is not installed in this environment.
    """
    try:
        return importlib.metadata.version(name)
    except importlib.metadata.PackageNotFoundError as exc:
        raise PinError(f"Package '{name}' is not installed in this environment") from exc


def parse_requirements(text: str, source: str = "requirements") -> tuple[list[str], list[str]]:
    """Package names and included files ("-r other.in") from the text of a requirements .in file.

    Comments, blank lines, environment markers and version specifiers are ignored (the versions come
    from the installed packages). Names are de-duplicated ignoring case and "_" vs "-".

    Raises:
        PinError: for URLs, editable installs, extras, stray text, or a file that lists nothing.
    """
    names: list[str] = []
    includes: list[str] = []
    seen: set[str] = set()
    for number, raw in enumerate(text.splitlines(), start=1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        where = f"{source}:{number}"
        if line.startswith("-r"):
            target = line[2:].strip()
            if not target:
                raise PinError(f"{where}: '-r' needs a file name")
            includes.append(target)
            continue
        line = line.split(";", 1)[0].strip()
        if line.startswith("-") or "://" in line or "@" in line:
            raise PinError(f"{where}: unsupported line {line!r}; list plain package names")
        match = _NAME.match(line)
        if match is None:
            raise PinError(f"{where}: {line!r} does not start with a package name")
        rest = line[match.end():].strip()
        if rest.startswith("["):
            raise PinError(f"{where}: extras such as {rest.split(']')[0]}] are not supported")
        if rest and rest[0] not in "=<>!~":
            raise PinError(f"{where}: unexpected text {rest!r} after the package name")
        key = normalize(match.group(0))
        if key not in seen:
            seen.add(key)
            names.append(match.group(0))
    if not names and not includes:
        raise PinError(f"{source} lists no packages")
    return names, includes


def pin_names(names: list[str], lookup: Callable[[str], str] = installed_version) -> list[str]:
    """`name==version` lines for every name, from `lookup`.

    Raises:
        PinError: listing every package that is not installed.
    """
    pins: list[str] = []
    missing: list[str] = []
    for name in names:
        try:
            pins.append(f"{name}=={lookup(name)}")
        except PinError:
            missing.append(name)
    if missing:
        raise PinError(f"Not installed in this environment: {missing}. Install them first (pip install -r <file>.in)")
    return pins


def render(source: str, includes: list[str], pins: list[str]) -> str:
    """The text of a pinned requirements file (no timestamp, so the output is reproducible)."""
    header = [
        f"# Generated by `python -m src.pin_requirements` from {source}.",
        f"# Do not edit by hand: edit {source} and run the command again.",
        "",
    ]
    lines = [*header, *[f"-r {PIN_FILES[include]}" for include in includes], *pins]
    return "\n".join(lines) + "\n"


def run_pin(
    root: str | Path = ".", lookup: Callable[[str], str] = installed_version
) -> dict[str, list[str]]:
    """Write requirements.txt (and the dev/notebook files, if their .in files exist).

    All files are prepared before any is written, so a failure leaves the existing files unchanged.

    Returns:
        {output file: its non-comment lines}

    Raises:
        PinError: for a missing requirements.in, unreadable or invalid files, an include of an unknown or
            missing file, packages that are not installed, or an unwritable output file.
    """
    base = Path(root)
    if not (base / REQUIRED_INPUT).is_file():
        raise PinError(f"{REQUIRED_INPUT} not found in {base.resolve()}")

    prepared: dict[str, str] = {}
    for source, target in PIN_FILES.items():
        path = base / source
        if not path.is_file():
            continue
        try:
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError) as exc:
            raise PinError(f"Could not read {path}: {exc}") from exc
        names, includes = parse_requirements(text, source)
        for include in includes:
            if include not in PIN_FILES:
                raise PinError(f"{source} includes unknown file '{include}'; allowed: {sorted(PIN_FILES)}")
            if not (base / include).is_file():
                raise PinError(f"{source} includes {include}, which does not exist")
        prepared[target] = render(source, includes, pin_names(names, lookup))

    for target, content in prepared.items():
        try:
            (base / target).write_text(content, encoding="utf-8", newline="\n")
        except OSError as exc:
            raise PinError(f"Cannot write {base / target}: {exc}") from exc
    return {
        target: [line for line in content.splitlines() if line and not line.startswith("#")]
        for target, content in prepared.items()
    }


def main() -> None:
    """Command-line entry point: `python -m src.pin_requirements` (run from the repository root)."""
    try:
        written = run_pin(".")
    except PinError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        sys.exit(1)
    for target, lines in written.items():
        print(f"Wrote {target}: {len(lines)} lines")


if __name__ == "__main__":
    main()